pub fn prepare(rate: f64) -> Result<Hall, &'static str> {
    if rate != SAMPLE_RATE {
        return Err("concert_hall requires its prepared 48000 Hz clock");
    }
    Hall::new(
        rate,
        LENGTHS,
        GAINS,
        POLES,
        INJECTION,
        TAPS.to_vec(),
        2.590996185297696,
    )
}
pub fn storage_seconds() -> f64 {
    let history = TAPS.iter().map(|t| t.0).chain(INJECTION).max().unwrap() + 1;
    // Graph delay budgets use f32-equivalent seconds; the hall stores f64.
    2. * (LENGTHS.iter().sum::<usize>() + history) as f64 / SAMPLE_RATE
}
pub fn data_entries() -> usize {
    16 * 4 + TAPS.len() * 3 + 2
}
